/** 시스템 글 (모든 사람 · 모든 차례에 같다) */
export function plannerGuideSystemPrompt() {
  const info = ['<플래너 안내>'];
  PLANNER_GUIDE_SECTIONS.forEach(([name, lines]) => {
    info.push(name);
    lines.forEach((l) => info.push(`· ${l}`));
    info.push('');
  });
  info[info.length - 1] = '</플래너 안내>';
  return [...RULES, '', ...info].join('\n');
}
